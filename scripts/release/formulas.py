#!/usr/bin/env python3
"""The Homebrew formulas for a release, from its checksums.

  formulas.py tap SHA256SUMS OUT    OUT/Formula/turboblake.rb (the command) and
                                    OUT/Formula/libturboblake.rb (the C library),
                                    from the release archives: gunta/homebrew-tap
  formulas.py core CRATE_SHA256     packaging/homebrew-core/turboblake.rb on the
                                    crates.io release (homebrew-core builds from source)

The version is bend/VERSION's. SHA256SUMS is the release's (sha256sum format).
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
VERSION = (ROOT / "bend" / "VERSION").read_text().strip()
# TURBOBLAKE_RELEASE_URL: another place with the archives (a test's file:// copy)
RELEASE = os.environ.get("TURBOBLAKE_RELEASE_URL") or \
    f"https://github.com/gunta/turboblake/releases/download/turboblake-v{VERSION}"
LICENSE = '''  license any_of: [
    "CC0-1.0",
    "Apache-2.0",
    { "Apache-2.0" => { with: "LLVM-exception" } },
  ]'''
# Homebrew's platforms, and the release target that serves each
TARGETS = [
    ("on_macos", "on_arm", "aarch64-apple-darwin"),
    ("on_macos", "on_intel", "x86_64-apple-darwin"),
    ("on_linux", "on_arm", "aarch64-unknown-linux-gnu"),
    ("on_linux", "on_intel", "x86_64-unknown-linux-gnu"),
]


def sums(path):
    out = {}
    for line in pathlib.Path(path).read_text().splitlines():
        if line.strip():
            digest, name = line.split(maxsplit=1)
            out[name.lstrip("*")] = digest
    return out


def platforms(digests, archive):
    """The on_macos/on_linux blocks, each platform's url and sha256."""
    blocks = []
    for os_ in ("on_macos", "on_linux"):
        inner = []
        for o, cpu, target in TARGETS:
            if o != os_:
                continue
            name = archive(target)
            if name not in digests:
                sys.exit(f"formulas.py: {name} is not in SHA256SUMS")
            inner.append(f'    {cpu} do\n      url "{RELEASE}/{name}"\n'
                         f'      sha256 "{digests[name]}"\n    end')
        blocks.append(f"  {os_} do\n" + "\n".join(inner) + "\n  end")
    return "\n\n".join(blocks)


def tap(sums_path, out):
    digests = sums(sums_path)
    formula = pathlib.Path(out) / "Formula"
    formula.mkdir(parents=True, exist_ok=True)
    (formula / "turboblake.rb").write_text(f'''# Generated by turboblake's release (scripts/release/formulas.py); edits are overwritten.
class Turboblake < Formula
  desc "BLAKE3 checksums, turbocharged: a drop-in b3sum with a Bend2 engine"
  homepage "https://gunta.github.io/turboblake/"
  version "{VERSION}"
{LICENSE}

{platforms(digests, lambda t: f"turboblake-{VERSION}-{t}.tar.gz")}

  def install
    bin.install "turboblake"
  end

  test do
    (testpath/"hello.txt").write "hello, world"
    digest = "a1a55887535397bf461902491c8779188a5dd1f8c3951b3d9cf6ecba194e87b0"
    assert_equal "#{{digest}}  hello.txt", shell_output("#{{bin}}/turboblake hello.txt").strip
    (testpath/"B3SUMS").write "#{{digest}}  hello.txt\\n"
    assert_equal "hello.txt: OK", shell_output("#{{bin}}/turboblake --check B3SUMS").strip
    assert_match version.to_s, shell_output("#{{bin}}/turboblake --version")
  end
end
''')
    (formula / "libturboblake.rb").write_text(f'''# Generated by turboblake's release (scripts/release/formulas.py); edits are overwritten.
class Libturboblake < Formula
  desc "BLAKE3 C library (blake3.h) with big inputs hashed on every core by a Bend2 engine"
  homepage "https://gunta.github.io/turboblake/"
  version "{VERSION}"
{LICENSE}

{platforms(digests, lambda t: f"libturboblake-{VERSION}-{t}.tar.gz")}

  depends_on "pkgconf" => :test

  def install
    # include/turboblake/blake3.h: beside Homebrew's own blake3, not over it
    include.install "include/turboblake"
    lib.install Dir["lib/*"]
  end

  test do
    (testpath/"test.c").write <<~C
      #include <stdio.h>
      #include "blake3.h"
      int main(void) {{
        blake3_hasher h;
        unsigned char out[BLAKE3_OUT_LEN];
        blake3_hasher_init(&h);
        blake3_hasher_update(&h, "abc", 3);
        blake3_hasher_finalize(&h, out, sizeof out);
        for (int i = 0; i < BLAKE3_OUT_LEN; i++) printf("%02x", out[i]);
        return 0;
      }}
    C
    flags = shell_output("pkgconf --cflags --libs --static libturboblake").chomp.split
    system ENV.cc, "test.c", "-o", "test", *flags
    assert_equal "6437b3ac38465133ffb63b75273a8db548c558465d79db03fd359c6cd5bd9d85", shell_output("./test")
  end
end
''')
    print(f"wrote {formula}/turboblake.rb and libturboblake.rb ({VERSION})")


def core(crate_sha):
    if not re.fullmatch(r"[0-9a-f]{64}", crate_sha):
        sys.exit(f"formulas.py: {crate_sha!r} is not a sha256")
    path = ROOT / "packaging" / "homebrew-core" / "turboblake.rb"
    s = path.read_text()
    s, n = re.subn(r'url "https://static\.crates\.io/crates/turboblake/turboblake-[^"]+\.crate"\n  sha256 "[0-9a-f]{64}"',
                   f'url "https://static.crates.io/crates/turboblake/turboblake-{VERSION}.crate"\n'
                   f'  sha256 "{crate_sha}"', s)
    if n != 1:
        sys.exit(f"formulas.py: {path}: no crates.io url and sha256")
    path.write_text(s)
    print(f"wrote {path} ({VERSION})")


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["tap"] and len(a) == 3:
        tap(a[1], a[2])
    elif a[:1] == ["core"] and len(a) == 2:
        core(a[1])
    else:
        sys.exit(__doc__)
