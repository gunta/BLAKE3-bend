#!/usr/bin/env python3
"""turboblake's one version, in every package that carries it.

bend/VERSION is the source; the manifests each registry reads hold copies:

  bend/crate/Cargo.toml       crates.io (generated by bend/rust/gen.sh from bend/VERSION)
  bend/node/package.json      npm
  bend/python/pyproject.toml  PyPI
  bend/python/setup.py        the module's __version__
  (bend/lib/CMakeLists.txt and the Go tag read bend/VERSION itself)

  scripts/release/version.py                 print the version
  scripts/release/version.py check [TAG]     every copy agrees (and with TAG, turboblake-vX.Y.Z)
  scripts/release/version.py set X.Y.Z       write it everywhere
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "bend" / "VERSION"
SEMVER = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-[0-9A-Za-z.-]+)?$")

# (file, pattern whose group 1 is the version) for the copies edited in place
COPIES = [
    ("bend/crate/Cargo.toml", re.compile(r'^version = "([^"]*)"$', re.M)),
    ("bend/python/pyproject.toml", re.compile(r'^version = "([^"]*)"$', re.M)),
    ("bend/python/setup.py", re.compile(r'^VERSION = "([^"]*)"$', re.M)),
]
NODE = "bend/node/package.json"


def current():
    return SOURCE.read_text().strip()


def copies():
    """Each copy's version, by file."""
    found = {}
    for rel, pat in COPIES:
        m = pat.search((ROOT / rel).read_text())
        found[rel] = m.group(1) if m else None
    found[NODE] = json.loads((ROOT / NODE).read_text()).get("version")
    return found


def check(tag=None):
    v = current()
    bad = [f"  bend/VERSION: {v!r} is not a version"] if not SEMVER.match(v) else []
    bad += [f"  {rel}: {got!r}" for rel, got in copies().items() if got != v]
    if tag is not None and tag != f"turboblake-v{v}":
        bad.append(f"  the tag {tag!r} is not turboblake-v{v}")
    if bad:
        print(f"turboblake {v}: these disagree (scripts/release/version.py set {v}):", file=sys.stderr)
        print("\n".join(bad), file=sys.stderr)
        return 1
    print(f"turboblake {v}: every package agrees" + (f" with {tag}" if tag else ""))
    return 0


def set_version(v):
    if not SEMVER.match(v):
        sys.exit(f"version.py: {v!r} is not X.Y.Z")
    SOURCE.write_text(v + "\n")
    for rel, pat in COPIES:
        path = ROOT / rel
        s = path.read_text()
        m = pat.search(s)
        if m is None:
            sys.exit(f"version.py: {rel}: no version line")
        path.write_text(s[:m.start(1)] + v + s[m.end(1):])
    path = ROOT / NODE
    s = path.read_text()
    # only the package's own "version", the first one, keeping the file's layout
    s, n = re.subn(r'^(  "version": )"[^"]*"', rf'\g<1>"{v}"', s, count=1, flags=re.M)
    if n != 1:
        sys.exit(f"version.py: {NODE}: no version")
    path.write_text(s)
    return check()


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args:
        print(current())
    elif args[0] == "check" and len(args) <= 2:
        sys.exit(check(args[1] if len(args) == 2 else None))
    elif args[0] == "set" and len(args) == 2:
        sys.exit(set_version(args[1]))
    else:
        sys.exit(__doc__)
