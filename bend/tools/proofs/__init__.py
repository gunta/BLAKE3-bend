"""Generators of the proof modules under bend/proof/ (tools/gen_laws.py
writes them): words.bend, the arithmetic; cpu.bend, the proof that the CPU's
8-lane tree is the scalar tree for every input; gpu.bend, the same for the
GPU's tree; spec.bend, that they are BLAKE3's tree; keyed.bend, the keyed
modes. Each is written without the counter's high word and threaded with it
by hi.py."""
import functools
import re

from . import words, reads, loop, group, leaf8, leaf32, tree, gpu, quads, gtree, spec, keyed, hi
from .common import L, laws_names

CPU_HEAD = '''\
# The CPU tree, for every input
# =============================
#
# GENERATED by tools/gen_laws.py (tools/proofs/): edit the generator.
#
# cpu.at: for every array and every span, H.hash's tree (tree8: 8 chunks at
# once through compress8, 32-chunk leaves, node kinds from a U32 copy of the
# depth) is blake3.bend's scalar tree (tree1, one chunk at a time). In order:
#
# - Reads hand their array back (get.eta, ld.eta), and lane l of the 8-lane
#   load is the scalar block of chunk l (ld8.words, b128.lane).
# - Lane l of the 8-lane chunk loop is the scalar loop of chunk l (loop.l*),
#   so lane l of a group is chunk c + l's chain (gl.l*).
# - An 8- or 32-chunk leaf is tree1 over its chunks, where the span holds it
#   whole (leaf8.eq, leaf32.eq).
# - Node by node, tree8 splits where tree1 does (cpu.tree), with c + n <= nch
#   kept down the tree through the U32 values (words.bend).
#
# Arrays are linear in proofs as in code: a proof that reads one array often
# takes copies of it (dup.w, wits, clone.w) and moves facts back with tr.

import Base
import ../blake3.bend as B3
import ../LAWS.bend as Laws
import ./words.bend as A
'''


def cv8_pat():
    return ", ".join(f"h{l}_{i}" for i in range(8) for l in range(L))


def b128_pat():
    return ", ".join(f"m{l}_{i}" for i in range(16) for l in range(L))


def lanes():
    """compress8.lane and par8.lane, proven here (PROOF.bend delegates)."""
    cv8, b128 = cv8_pat(), b128_pat()
    xs, ys = cv8.replace("h", "x"), cv8.replace("h", "y")
    c8 = "".join(f"    case L{l}{{}} B3.CV8{{{cv8}}} B3.B128{{{b128}}}:\n      {{==}}\n" for l in range(L))
    p8 = "".join(f"    case L{l}{{}} B3.CV8{{{xs}}} B3.CV8{{{ys}}}:\n      {{==}}\n" for l in range(L))
    return f'''
# The 8-lane path
# ---------------

law compress8.lane:
  for +l: Lane
  for +cv: B3.CV8
  for +m: B3.B128
  for +ctr: U32
  for +step: U32
  for +blen: U32
  for +flags: U32
  {{cv.at(l, B3.compress8(cv, m, ctr, step, blen, flags)) ==
    B3.compress(cv.at(l, cv), m.at(l, m), (ctr + (step * Lane.u32(l) : U32) : U32),
      0, blen, flags) : B3.CV}}

def compress8.lane(l, cv, m, ctr, step, blen, flags):
  match l cv m:
{c8}
law par8.lane:
  for +l: Lane
  for +x: B3.CV8
  for +y: B3.CV8
  {{cv.at(l, B3.par8(x, y)) == par.ref(l, x, y) : B3.CV}}

def par8.lane(l, x, y):
  match l x y:
{p8}'''


def words_file():
    return words.text()


@functools.cache
def cpu_hi():
    body = (reads.HEAD + reads.ld_eta() + reads.ld8_words() + reads.b128_lane() + lanes() + reads.WITS +
            loop.text() + group.text() + leaf8.text() + leaf32.text() + tree.text())
    return hi.module(CPU_HEAD + laws_names(body), "import ./words.bend as A\n")


def cpu_file():
    return cpu_hi()[0]


GPU_HEAD = '''\
# The GPU tree, for every input
# =============================
#
# GENERATED by tools/gen_laws.py (tools/proofs/): edit the generator.
#
# gpu.at: for every array and every span, hash1's tree (treeg: whole, full
# subtrees of 4, 16 or 64 chunks to one lane each, bigger ones at leaf level
# 6 to strided lanes) is blake3.bend's scalar tree. In order:
#
# - A lane's chunk (gch) and its flat leaves (g4, g16, g64: chains of four
#   under parents) hand their array back, and are tree1 over their chunks
#   where the span holds them whole (g4.eq, g16.eq, g64.eq).
# - A strided lane (quad) is four 16-chunk subtrees st chunks apart, and a
#   fork of 2^r lanes (qtree) is four scalar subtrees of 16 << r chunks, by
#   induction on r: a join pairs its halves' groups into the next level's
#   subtrees (qt). A GQuad node is tree1 halved twice (gquad.eq).
# - Node by node, treeg splits where tree1 does (gpu.tree), its kind from a
#   U32 copy of the depth and the leaf level, as in the CPU tree's proof.
#
# The reads, witnesses and node invariants are cpu.bend's (C.).

import Base
import ../blake3.bend as B3
import ../LAWS.bend as Laws
import ./words.bend as A
import ./cpu.bend as C
'''


@functools.cache
def gpu_hi():
    names = set(re.findall(r"^(?:def|law) ([\w.]+)", cpu_file(), re.M))
    pat = re.compile(r"(?<![\w.])(" + "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True)) + r")(?![\w.])")
    body = laws_names(gpu.text() + quads.text() + gtree.text())
    text = GPU_HEAD + "".join(l if l.lstrip().startswith("#") else pat.sub(r"C.\1", l)
                              for l in body.splitlines(keepends=True))
    return hi.module(text, "import ./cpu.bend as C\n", {"C." + n for n in cpu_hi()[1]})


def gpu_file():
    return gpu_hi()[0]


def spec_file():
    ext = {"C." + n for n in cpu_hi()[1]} | {"G." + n for n in gpu_hi()[1]}
    return hi.module(spec.text(), "import ./gpu.bend as G\n", ext)[0]


def keyed_file():
    return keyed.text(cpu_file(), spec_file())
