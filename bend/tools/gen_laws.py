TREES = '''\
# Tree shapes
# -----------
#
# A Shape is a tree with the chunks at its leaves, left to right, so a law
# about Shapes holds for any compression function. BLAKE3's tree over the
# chunks 0..r (r + 1 of them, at most 2^k) is tree(digits(k, r, [])): reading
# the k binary digits of r from the top, a 1 at a node of depth d means the
# last chunk is past the first 2^(d-1), so the node is a parent of the
# complete tree over those 2^(d-1) chunks and the tree over the rest; a 0
# means every chunk fits in the left half, and the node is that half. That is
# blake3.bend's tree1 split (big: n > 2^p, for n = r + 1 chunks): the law
# tree1.digits proves the two agree.

type Shape is Data:
  Tip{}
  Fork{l: Shape, r: Shape}

# The complete tree over 2^k chunks.
def full(+k: Nat) -> Shape:
  match k:
    case 0n:
      Tip{}
    case 1n+p:
      Fork{full(p), full(p)}

# BLAKE3's tree for the binary digits ds (most significant first) of the
# last chunk's index.
def tree(+ds: List<&2, Bool>) -> Shape:
  match ds:
    case Nil{}:
      Tip{}
    case Con{True{}, rest}:
      Fork{full(List.length(&2, Bool, rest)), tree(rest)}
    case Con{False{}, rest}:
      tree(rest)

def half(+v: Nat) -> Nat:
  match v:
    case 0n:
      0n
    case 1n+p:
      match p:
        case 0n:
          0n
        case 1n+q:
          1n+half(q)

def odd(+v: Nat) -> Bool:
  match v:
    case 0n:
      False{}
    case 1n+p:
      match p:
        case 0n:
          True{}
        case 1n+q:
          odd(q)

# v >> k
def shr(+k: Nat, +v: Nat) -> Nat:
  match k:
    case 0n:
      v
    case 1n+p:
      shr(p, half(v))

# The low k binary digits of v, most significant first, in front of acc.
def digits(+k: Nat, +v: Nat, +acc: List<&2, Bool>) -> List<&2, Bool>:
  match k:
    case 0n:
      acc
    case 1n+p:
      digits(p, half(v), odd(v) <> acc)

# blake3.bend's tree1 on Nat chunk counts: a node of depth k over n chunks
# (1 <= n <= 2^k) is a parent when n > 2^(k-1) (`big`), of the complete
# tree over the first 2^(k-1) chunks and the tree over the rest.
def pow2(+k: Nat) -> Nat:
  match k:
    case 0n:
      1n
    case 1n+p:
      Nat.double(pow2(p))

def big(+k: Nat, +n: Nat) -> Bool:
  match k:
    case 0n:
      False{}
    case 1n+p:
      Nat.is_gt(n, pow2(p))

def tree1(+k: Nat, b: Bool, +n: Nat) -> Shape:
  match k b:
    case 0n _:
      Tip{}
    case 1n+p False{}:
      tree1(p, big(p, n), n)
    case 1n+p True{}:
      +h = pow2(p)
      +n2 = Nat.sub(n, h)
      Fork{tree1(p, big(p, h), h), tree1(p, big(p, n2), n2)}

# tree(digits) is tree1's rule: the node of depth k over r + 1 chunks
# (r < 2^k) is the tree of r's k digits, for every chunk count.
law tree1.digits:
  for +k: Nat
  for +r: Nat
  for e: {shr(k, r) == 0n : Nat}
  {tree1(k, big(k, 1n+r), 1n+r) == tree(digits(k, r, [])) : Shape}

# Every leaf of t, made the complete tree over 2^k chunks.
def grow(t: Shape, +k: Nat) -> Shape:
  match t:
    case Tip{}:
      full(k)
    case Fork{l, r}:
      Fork{grow(l, k), grow(r, k)}

# The tree over a big input's segments, t, with each segment's own tree at
# its leaf: every one but the last (rightmost) is complete; the last is
# BLAKE3's tree over the digits lo of the last chunk's offset in it.
def graft(t: Shape, +lo: List<&2, Bool>) -> Shape:
  match t:
    case Tip{}:
      tree(lo)
    case Fork{l, r}:
      Fork{grow(l, List.length(&2, Bool, lo)), graft(r, lo)}

# Segments (ADR 0004): with 2^k chunks a segment, the tree over chunks
# 0..r is the parts' own BLAKE3 tree over segments 0..(r >> k), each segment
# a complete subtree but the last. So b3sum may hash a file's 1 GiB parts
# (k = 20) as separate spans and merge them with parents, for any file size.
law segments:
  for +k: Nat
  for +j: Nat
  for +r: Nat
  {tree(digits(Nat.add(k, j), r, [])) ==
    graft(tree(digits(j, shr(k, r), [])), digits(k, r, [])) : Shape}

# The r + 1 chunks, one leaf each.
def leaves(+r: Nat) -> List<&2, Shape>:
  match r:
    case 0n:
      [Tip{}]
    case 1n+p:
      Tip{} <> leaves(p)

# One level of a GPU reduction: neighbours pair up, an odd last one goes up
# unchanged.
def pairs(+xs: List<&2, Shape>) -> List<&2, Shape>:
  match xs:
    case Nil{}:
      Nil{}
    case Con{x, rest}:
      match rest:
        case Nil{}:
          [x]
        case Con{y, more}:
          Fork{x, y} <> pairs(more)

# k levels of pairs.
def reduce(+k: Nat, +xs: List<&2, Shape>) -> List<&2, Shape>:
  match k:
    case 0n:
      xs
    case 1n+p:
      reduce(p, pairs(xs))

# v complete trees over 2^len(lo) chunks each, then BLAKE3's tree over lo.
def row(+v: Nat, +lo: List<&2, Bool>) -> List<&2, Shape>:
  List.append(&2, Shape, List.replicate(Shape, v, full(List.length(&2, Bool, lo))),
    [tree(lo)])

# Levels: after k levels of pairing the r + 1 chunk leaves, the row holds
# r >> k complete subtrees of 2^k chunks, then BLAKE3's tree over the rest.
law levels:
  for +k: Nat
  for +r: Nat
  {reduce(k, leaves(r)) == row(shr(k, r), digits(k, r, [])) : List<&2, Shape>}

# So once 2^k > r, a level-by-level GPU reduction is BLAKE3's tree.
law levels.root:
  for +k: Nat
  for +r: Nat
  for e: {shr(k, r) == 0n : Nat}
  {reduce(k, leaves(r)) == [tree(digits(k, r, []))] : List<&2, Shape>}
'''

