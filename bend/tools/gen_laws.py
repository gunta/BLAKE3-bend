def digests():
    cases = json.loads(VECTORS.read_text())["cases"]
    return {c["input_len"]: c["hash"][:64] for c in cases}


def cv8_pat():
    return ", ".join(f"h{l}_{i}" for i in range(8) for l in range(L))


def b128_pat():
    return ", ".join(f"m{l}_{i}" for i in range(16) for l in range(L))


def lane_cv(l, src="h"):
    return "B3.CV{" + ", ".join(f"{src}{l}_{i}" for i in range(8)) + "}"


def lane_m(l):
    return "B3.M16{" + ", ".join(f"m{l}_{i}" for i in range(16)) + "}"


def schedules():
    """Rows 1..6 of MSG_SCHEDULE, read from the official C code, so the law
    checks perm against an independent copy of the table."""
    src = (ROOT.parent / "c" / "blake3_impl.h").read_text()
    body = src[src.index("MSG_SCHEDULE[7][16] = {"):]
    body = body[body.index("{") + 1:body.index("};")]
    rows = [[int(x) for x in r.split("}")[0].split(",")]
            for r in body.split("{")[1:]]
    assert len(rows) == 7 and rows[0] == list(range(16))
    return rows[1:]


