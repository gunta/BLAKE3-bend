#!/usr/bin/env python3
"""Generates bend/LAWS.bend and bend/PROOF.bend.

The laws need the official vectors' digests and the 64- and 128-field
patterns of CV8 and B128, so they are written out here; the rest is plain
Bend kept verbatim in the templates below. `bend PROOF.bend` is the gate.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
VECTORS = ROOT.parent / "test_vectors" / "test_vectors.json"

L = 8

# The known-answer lengths, picked to reach every node kind of the small
# trees (the checker computes ~1.5 compressions a second): an empty input,
# block edges, a partial chunk, Split over a short last chunk, Down, two
# levels of Split, and a Leaf8 (compress8, par8, fold8) beside a Down chain.
KAT_HASH = [0, 1, 64, 65, 1023, 1025, 2049, 3073, 8193]
# The GPU tree's GSplit and GDown (its flat leaves start at 64 MiB; g4 has
# its own law below).
KAT_HASH1 = [0, 2049]


def digests():
    cases = json.loads(VECTORS.read_text())["cases"]
    return {c["input_len"]: c["hash"][:64] for c in cases}


def cv8_pat():
    return ", ".join(f"h{l}_{i}" for i in range(8) for l in range(L))


def b128_pat():
    return ", ".join(f"m{l}_{i}" for i in range(16) for l in range(L))


def lane_cv(l, src="h"):
    return "B3.CV{" + ", ".join(f"{src}{l}_{i}" for i in range(8)) + "}"


def lane_m(l):
    return "B3.M16{" + ", ".join(f"m{l}_{i}" for i in range(16)) + "}"


def schedules():
    """Rows 1..6 of MSG_SCHEDULE, read from the official C code, so the law
    checks perm against an independent copy of the table."""
    src = (ROOT.parent / "c" / "blake3_impl.h").read_text()
    body = src[src.index("MSG_SCHEDULE[7][16] = {"):]
    body = body[body.index("{") + 1:body.index("};")]
    rows = [[int(x) for x in r.split("}")[0].split(",")]
            for r in body.split("{")[1:]]
    assert len(rows) == 7 and rows[0] == list(range(16))
    return rows[1:]


