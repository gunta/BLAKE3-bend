#!/bin/sh
# Regenerates the GPU backend's kernels for libturboblake (ADR 0017), from
# the native kernels in bend/ref: csrc/turboblake_kernels.h holds the Metal
# source (b3core.h + b3.metal, compiled by the Metal driver at run time) and
# the CUDA kernels as PTX (compiled by libcuda for the GPU it finds), and
# csrc/b3core.h the compression the backend also merges with on the CPU.
# Needs an LLVM clang with the NVPTX backend (Homebrew's llvm, or CLANG=).
# Run it after any change to bend/ref's kernels, then commit csrc.
set -e
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
ref="$root/bend/ref"
CLANG="${CLANG:-/opt/homebrew/opt/llvm/bin/clang}"
out="$here/csrc/turboblake_kernels.h"
mkdir -p "$here/csrc" "$ref/cuda/build"
# PTX for sm_75 (ISA 6.4), which every GPU from Turing on JIT-compiles, with
# the two leaf sizes the library runs.
CLANG="$CLANG" PTX_ARCH=sm_75 PTX_ISA=ptx64 PTX_DEFS=-DB3_LIB "$ref/cuda/build.sh" --ptx
python3 - "$ref" "$out" <<'PY'
import pathlib, sys
ref, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
metal = (ref / "b3core.h").read_text() + (ref / "metal" / "b3.metal").read_text()
ptx = (ref / "cuda" / "build" / "b3.ptx").read_text()
def lit(name, text):
    lines = []
    for line in text.splitlines(keepends=True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append(f'    "{esc}"')
    return f"static const char {name}[] =\n" + "\n".join(lines) + ";\n"
out.write_text(
    "// Generated by bend/lib/gen_gpu.sh from bend/ref: do not edit.\n"
    "// The Metal kernels' source (b3core.h + metal/b3.metal) and the CUDA\n"
    "// kernels (cuda/b3.cu) as PTX, for turboblake_gpu.c.\n"
    "#ifndef TURBOBLAKE_KERNELS_H\n#define TURBOBLAKE_KERNELS_H\n\n"
    + lit("tbg_metal_src", metal) + "\n" + lit("tbg_ptx", ptx) + "\n#endif\n")
PY
cp "$ref/b3core.h" "$here/csrc/b3core.h"
cp "$here/turboblake_gpu.c" "$here/turboblake_gpu.h" "$here/csrc/"
echo "wrote $out ($(wc -c < "$out") bytes)"
